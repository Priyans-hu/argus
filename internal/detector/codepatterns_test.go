func TestKeys(t *testing.T) {
	input := map[string]string{
		"a": "value1",
		"b": "value2",
		"c": "value3",
	}

	result := keys(input)

	if len(result) != 3 {
		t.Errorf("keys() returned %d items, expected 3", len(result))
	}

	// Check all keys are present
	hasKey := func(k string) bool {
		for _, r := range result {
			if r == k {
				return true
			}
		}
		return false
	}

	for k := range input {
		if !hasKey(k) {
			t.Errorf("keys() missing key: %s", k)
		}
	}
}

func TestLimitSlice(t *testing.T) {
	tests := []struct {
		name     string
		input    []string
		limit    int
		expected int
	}{
		{
			name:     "limit smaller than input",
			input:    []string{"a", "b", "c", "d", "e"},
			limit:    3,
			expected: 3,
		},
		{
			name:     "limit larger than input",
			input:    []string{"a", "b"},
			limit:    5,
			expected: 2,
		},
		{
			name:     "limit equals input",
			input:    []string{"a", "b", "c"},
			limit:    3,
			expected: 3,
		},
		{
			name:     "empty input",
			input:    []string{},
			limit:    3,
			expected: 0,
		},
	}

	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			result := limitSlice(tt.input, tt.limit)
			if len(result) != tt.expected {
				t.Errorf("limitSlice() returned %d items, expected %d", len(result), tt.expected)
			}
		})
	}
}
