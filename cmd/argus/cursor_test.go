package main

import (
	"os"
	"path/filepath"
	"strings"
	"testing"

	"github.com/Priyans-hu/argus/internal/merger"
)

const (
	cursorRule  = ".cursor/rules/argus.mdc"
	cursorFront = "---\ndescription: Project context generated by argus\nalwaysApply: true\n---\n"
)

func TestCursorRuleKeepsFrontmatterOutsideAutoBlock(t *testing.T) {
	resetFlags(t)
	out, errOut := captureOutput(t)
	root := t.TempDir()

	generate(t, root, "cursor")
	first := readFile(t, root, cursorRule)
	checkMarked(t, first)
	if !strings.HasPrefix(first, cursorFront+merger.AutoStartMarker+"\n") || !strings.HasSuffix(first, merger.AutoEndMarker+"\n") {
		t.Fatalf("want frontmatter, then the AUTO block:\n%s", first)
	}
	if _, err := os.Stat(filepath.Join(root, ".cursorrules")); !os.IsNotExist(err) {
		t.Errorf(".cursorrules was written (err %v)", err)
	}

	out.Reset()
	generate(t, root, "cursor")
	if readFile(t, root, cursorRule) != first || out.String() != "✅ "+cursorRule+" is up to date\n" {
		t.Errorf("rerun changed the rule or printed %q", out)
	}

	edited := "---\ndescription: mine\nglobs: src/**\nalwaysApply: false\n---\nABOVE\n" +
		strings.TrimPrefix(strings.Replace(first, "# Project", "# Stale", 1), cursorFront) + "BELOW\n"
	writeFiles(t, root, map[string]string{cursorRule: edited})
	generate(t, root, "cursor")
	want := strings.Replace(edited, "# Stale", "# Project", 1)
	if got := readFile(t, root, cursorRule); got != want {
		t.Errorf("rerun lost user edits:\n%s\nwant\n%s", got, want)
	}
	if errOut.Len() != 0 {
		t.Errorf("unexpected notices: %q", errOut)
	}
}

func TestCursorRuleAdoptsUnmarkedFile(t *testing.T) {
	resetFlags(t)
	_, errOut := captureOutput(t)
	root := t.TempDir()
	front := "---\ndescription: team rules\nalwaysApply: true\n---\n"
	writeFiles(t, root, map[string]string{cursorRule: front + "Use tabs.\n"})

	generate(t, root, "cursor")
	got := readFile(t, root, cursorRule)
	checkMarked(t, got)
	if !strings.HasPrefix(got, front+merger.AutoStartMarker+"\n") || !strings.HasSuffix(got, merger.AutoEndMarker+"\n\nUse tabs.\n") {
		t.Errorf("want frontmatter, AUTO block, old body:\n%s", got)
	}
	if !strings.Contains(errOut.String(), cursorRule+" had no argus markers") {
		t.Errorf("no adoption notice: %q", errOut)
	}

	generate(t, root, "cursor")
	if again := readFile(t, root, cursorRule); again != got {
		t.Errorf("second run changed the adopted file:\n%s", again)
	}
}

func TestCursorrulesIsLeftAloneWithNotice(t *testing.T) {
	resetFlags(t)
	_, errOut := captureOutput(t)
	watchNotified = map[string]bool{}
	root := t.TempDir()
	writeFiles(t, root, map[string]string{".cursorrules": "old rules\n"})

	generate(t, root, "claude")
	if errOut.Len() != 0 {
		t.Errorf("notice without the cursor format: %q", errOut)
	}
	for range 3 {
		generate(t, root, "cursor")
	}
	if got := readFile(t, root, ".cursorrules"); got != "old rules\n" {
		t.Errorf(".cursorrules changed: %q", got)
	}
	want := "ℹ️  .cursorrules is no longer written by argus and was left unchanged (rules now go to .cursor/rules/argus.mdc; " +
		"delete the old file once its rules are moved, since a stale one can shadow AGENTS.md in tools like Zed)\n"
	if errOut.String() != want {
		t.Errorf("stderr = %q, want the notice once", errOut)
	}
}
